## The Nim examples of the OpenSpec specs, run against the code.
##
## Every ```nim block in `openspec/specs/*/spec.md` is an example. When a ```text block follows it,
## what the example prints must equal that text. The examples run in one generated program
## (`tools/specsuite_gen.nim`, not committed), where `echo` is captured and, for a table, its HTML
## too, so the spec page can show the table each example makes.
##
##   nim r tools/specexamples.nim                 # run them, exit 1 if one fails
##   nim r tools/specexamples.nim --update        # write the actual outputs into the specs
##   nim r tools/specexamples.nim --json:out.json # also save the results, for docs/specs.nim
##   nim r tools/specexamples.nim --changes       # also the examples of open changes (may fail)

import std/[os, osproc, strutils, json, algorithm, parseopt]

type
  Example* = object
    path*: string           ## spec.md, relative to the repo root
    capability*: string
    line*: int              ## 1-based line of the ```nim fence
    code*: string
    expected*: string
    hasExpected*: bool
    textStart*, textEnd*: int   ## 0-based lines of the ```text body, for --update

let root* = currentSourcePath().parentDir.parentDir

proc parseExamples*(path, rel, capability: string): seq[Example] =
  let lines = readFile(path).splitLines
  var i = 0
  while i < lines.len:
    if lines[i].strip == "```nim":
      var ex = Example(path: rel, capability: capability, line: i + 1)
      var code: seq[string]
      inc i
      while i < lines.len and lines[i].strip != "```":
        code.add lines[i]
        inc i
      ex.code = code.join("\n")
      var j = i + 1
      while j < lines.len and lines[j].strip.len == 0: inc j
      if j < lines.len and lines[j].strip == "```text":
        ex.hasExpected = true
        ex.textStart = j + 1
        var k = j + 1
        var txt: seq[string]
        while k < lines.len and lines[k].strip != "```":
          txt.add lines[k]
          inc k
        ex.textEnd = k
        ex.expected = txt.join("\n")
        i = k
      result.add ex
    inc i

proc collect*(withChanges = false): seq[Example] =
  var dirs = @[("openspec/specs", "")]
  if withChanges:
    for kind, p in walkDir(root / "openspec" / "changes"):
      if kind == pcDir and p.lastPathPart != "archive":
        dirs.add ("openspec/changes/" & p.lastPathPart & "/specs", p.lastPathPart)
  for (dir, _) in dirs:
    var caps: seq[string]
    for kind, p in walkDir(root / dir):
      if kind == pcDir and fileExists(p / "spec.md"): caps.add p.lastPathPart
    caps.sort
    for cap in caps:
      result.add parseExamples(root / dir / cap / "spec.md", dir & "/" & cap & "/spec.md", cap)

proc generate(examples: seq[Example]): string =
  result = """
# Generated by tools/specexamples.nim: every example of the specs, `echo` captured.
import std/[json, strutils, sugar, os]
import tabelline, tabelline/datasets
from ../docs/review import reviewVersion, reviewSettings, `$`   # the review mode's examples
var captured {.used.}: string
var shown {.used.}: seq[string]
proc echo(args: varargs[string, `$`]) {.used.} =
  captured.add args.join("") & "\n"
proc echo(t: Tabella) {.used.} =
  captured.add t.toText & "\n"
  shown.add t.toHtml(withStyle = false)   # the page writes tabellaStyle once
var results = newJArray()
"""
  for k, ex in examples:
    # an example that does not compile (an open change not built yet) fails alone, at run time
    result.add "\ntemplate exampleBody" & $k & "() =\n"
    for l in ex.code.splitLines: result.add "  " & l & "\n"
    result.add "  discard\n"
    result.add "proc example" & $k & "() =\n  when compiles(exampleBody" & $k & "()): exampleBody" & $k &
      "()\n  else: raise newException(CatchableError, \"does not compile (not built yet?)\")\n"
    result.add "captured = \"\"\nshown = @[]\n"
    result.add "try:\n  example" & $k & "()\n  results.add %*{\"ok\": true, \"out\": captured.strip(leading = false), \"html\": shown}\n"
    result.add "except CatchableError as e:\n  results.add %*{\"ok\": false, \"out\": captured & \"\\nError: \" & e.msg, \"html\": shown}\n"
  result.add "\nwriteFile(\"" & (root / "tools" / "specsuite_out.json") & "\", $results)\n"

proc run*(examples: seq[Example]): JsonNode =
  ## Runs the examples in one program, returns one result per example: ok, out, html.
  let src = root / "tools" / "specsuite_gen.nim"
  writeFile(src, generate(examples))
  let (output, code) = execCmdEx("nim r --hints:off --warnings:off " & quoteShell(src), workingDir = root)
  if code != 0:
    quit "the spec examples do not compile:\n" & output
  result = parseJson(readFile(root / "tools" / "specsuite_out.json"))
  removeFile(root / "tools" / "specsuite_out.json")

proc verdict*(ex: Example, r: JsonNode): string =
  if not r["ok"].getBool: "error"
  elif not ex.hasExpected: "ran"
  elif r["out"].getStr.strip(leading = false) == ex.expected.strip(leading = false): "pass"
  else: "fail"

when isMainModule:
  var update, withChanges = false
  var jsonOut = ""
  for kind, key, val in getopt():
    case key
    of "update": update = true
    of "changes": withChanges = true
    of "json": jsonOut = val
    else: discard
  let examples = collect(withChanges)
  let res = run(examples)
  var failed = 0
  var report = newJArray()
  for k, ex in examples:
    let v = verdict(ex, res[k])
    if v in ["fail", "error"] and not ex.path.startsWith("openspec/changes"): inc failed
    echo v.alignLeft(6), ex.path, ":", ex.line
    if v in ["fail", "error"]:
      echo "  expected:\n", ex.expected.indent(4), "\n  actual:\n", res[k]["out"].getStr.indent(4)
    report.add %*{"path": ex.path, "capability": ex.capability, "line": ex.line, "code": ex.code,
                  "expected": ex.expected, "out": res[k]["out"], "html": res[k]["html"], "verdict": v}
  if update:
    # rewrite the ```text blocks (and add missing ones) from the bottom up, file by file
    var byPath: seq[string]
    for ex in examples:
      if ex.path notin byPath: byPath.add ex.path
    for p in byPath:
      var lines = readFile(root / p).splitLines
      for k in countdown(examples.high, 0):
        let ex = examples[k]
        if ex.path != p or not res[k]["ok"].getBool: continue
        let outLines = res[k]["out"].getStr.strip(leading = false).splitLines
        if ex.hasExpected:
          lines[ex.textStart ..< ex.textEnd] = outLines
        elif res[k]["out"].getStr.strip.len > 0:
          var fenceEnd = ex.line   # 0-based index of the closing ``` of the nim block
          while lines[fenceEnd].strip != "```": inc fenceEnd
          let fenced = @["", "```text"] & outLines & @["```"]
          for m in countdown(fenced.high, 0): lines.insert(fenced[m], fenceEnd + 1)
      writeFile(root / p, lines.join("\n"))
    echo "updated the expected outputs"
  if jsonOut.len > 0: writeFile(jsonOut, $report)
  echo examples.len, " examples, ", failed, " failing"
  if failed > 0 and not update: quit 1
